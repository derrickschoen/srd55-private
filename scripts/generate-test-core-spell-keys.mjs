import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const testsRoot = path.join(projectRoot, 'tests');
const digestPath = path.join(
  projectRoot,
  'src/catalog/bundled-content-digest-v1.expected.ts',
);
const outputPath = path.join(
  projectRoot,
  'src/db/test-core-spell-content-keys.generated.ts',
);

async function filesUnder(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries
    .sort((left, right) => left.name.localeCompare(right.name))
    .map((entry) => {
      const target = path.join(directory, entry.name);
      if (entry.isDirectory()) return filesUnder(target);
      return entry.isFile() ? [target] : [];
    }));
  return nested.flat();
}

const expectedDigestSource = await readFile(digestPath, 'utf8');
const catalogKeys = [...expectedDigestSource.matchAll(
  /"kind":"spell","contentKey":"([^"]+)"/g,
)].map((match) => match[1]);
if (catalogKeys.length === 0 || new Set(catalogKeys).size !== catalogKeys.length) {
  throw new Error('Could not derive a unique bundled spell catalog from the pinned digest.');
}

const testText = (await Promise.all(
  (await filesUnder(testsRoot)).map((file) => readFile(file, 'utf8')),
)).join('\n');
const referencedKeys = catalogKeys.filter((contentKey) =>
  testText.includes(contentKey)
);

const generated = `// Generated by: node scripts/generate-test-core-spell-keys.mjs
// Source: bundled spell content keys from the pinned digest that occur anywhere under tests/.
import type { ContentKey } from '../domain/ids';

export const TEST_CORE_SPELL_CONTENT_KEYS: readonly ContentKey[] = Object.freeze([
${referencedKeys.map((contentKey) => `  '${contentKey}' as ContentKey,`).join('\n')}
]);
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8');
  if (current !== generated) {
    throw new Error(
      'The test-core spell keep-list is stale. Run node scripts/generate-test-core-spell-keys.mjs.',
    );
  }
} else {
  await writeFile(outputPath, generated);
}
