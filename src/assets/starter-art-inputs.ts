export type StarterArtKind =
  | 'token'
  | 'map'
  | 'terrain'
  | 'fog'
  | 'focus'
  | 'event';

export type PixelPalette =
  | 'pc-blue'
  | 'monster-red'
  | 'stone'
  | 'wood'
  | 'terrain'
  | 'hazard'
  | 'fog'
  | 'focus'
  | 'adjudicated';

export interface StarterArtInput {
  readonly id: AssetId;
  readonly title: string;
  readonly kind: StarterArtKind;
  readonly palette: PixelPalette;
  /** Sixteen 16-pixel rows: # silhouette, + accent, o highlight, . empty. */
  readonly pixels: readonly string[];
}

const rows = (...value: readonly string[]): readonly string[] => {
  if (value.length !== 16 || value.some((row) => row.length !== 16 || /[^#+o.]/u.test(row))) {
    throw new Error('Starter-art inputs must be exactly 16×16 and use only #, +, o, and .');
  }
  return Object.freeze(value);
};

function input(
  id: string,
  title: string,
  kind: StarterArtKind,
  palette: PixelPalette,
  pixels: readonly string[],
): StarterArtInput {
  return Object.freeze({ id: assetId(id), title, kind, palette, pixels });
}

